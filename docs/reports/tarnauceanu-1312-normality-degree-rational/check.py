#!/usr/bin/env python3
"""Exact checks for Tarnauceanu's normality-degree rational-realization route.

Enumerates subgroups by adjoining generators, independently of the proposed
classification. Only integers, sets and Fraction are used as evidence.
"""
from collections import deque
from fractions import Fraction
from math import isqrt


def prime(n):
    return n >= 2 and all(n % d for d in range(2, isqrt(n) + 1))


def multiplicative_order(r, p):
    a = 1
    for k in range(1, p):
        a = a * r % p
        if a == 1:
            return k
    raise AssertionError((r, p))


def all_subgroups(p, B, r):
    """BFS in the subgroup lattice of the actual multiplication table.

Every subgroup is generated by some finite list of elements. At every visited
subgroup, adjoining one representative from each right coset explores all
one-generator extensions: <H,hg> = <H,g>. No classification formula is used.
    """
    m = 2**B
    n = p * m
    elements = range(n)
    powers = [pow(r, i, p) for i in range(m)]

    def multiply(x, y):
        a, i = divmod(x, m)
        b, j = divmod(y, m)
        return ((a + powers[i] * b) % p) * m + (i + j) % m

    mul = [[multiply(x, y) for y in elements] for x in elements]
    inv = []
    for x in elements:
        a, i = divmod(x, m)
        y = (-pow(r, -i, p) * a % p) * m + (-i % m)
        assert mul[x][y] == mul[y][x] == 0
        inv.append(y)
    assert all(mul[0][x] == mul[x][0] == x for x in elements)
    if n <= 32:
        assert all(mul[mul[x][y]][z] == mul[x][mul[y][z]]
                   for x in elements for y in elements for z in elements)

    def generated(gens):
        seen = {0}
        todo = deque([0])
        while todo:
            x = todo.popleft()
            for g in gens:
                y = mul[x][g]
                if y not in seen:
                    seen.add(y)
                    todo.append(y)
        return frozenset(seen)

    trivial = frozenset({0})
    generators = {trivial: ()}
    todo = deque([trivial])
    while todo:
        H = todo.popleft()
        unseen = set(elements) - H
        while unseen:
            g = min(unseen)
            unseen.difference_update(mul[h][g] for h in H)
            gens = generators[H] + (g,)
            K = generated(gens)
            if K not in generators:
                generators[K] = gens
                todo.append(K)

    subgroups = set(generators)
    normals = set()
    for H in subgroups:
        # All ambient conjugators are tested, not only the presentation generators.
        if all(mul[mul[g][h]][inv[g]] in H for g in elements for h in H):
            normals.add(H)
    assert trivial in normals and frozenset(elements) in normals
    return subgroups, normals


def direct_checks():
    cases = []
    for p in (3, 5, 7, 11, 13, 17):
        for t in range(1, 5):
            candidates = [r for r in range(2, p)
                          if multiplicative_order(r, p) == 2**t]
            if candidates:
                for B in range(t, 5):
                    cases.append((p, B, t, candidates[0]))
    cases.append((5, 5, 2, 2))  # The full realization recipe for x = 1/2.
    for p, B, t, r in cases:
        L, N = all_subgroups(p, B, r)
        expected_N = 2*B - t + 2
        expected_L = expected_N + p*t
        assert (len(N), len(L)) == (expected_N, expected_L), (p, B, t, r)
        # Also check the classification level by level after independent enumeration.
        m = 2**B
        P = frozenset(a*m for a in range(p))
        contains_P = [H for H in L if P <= H]
        assert len(contains_P) == B+1 and all(H in N for H in contains_P)
        remaining = L - set(contains_P)
        assert all(len(H & P) == 1 for H in remaining)
        for j in range(B+1):
            level = [H for H in remaining if len({h % m for h in H}) == 2**j]
            assert len(level) == (1 if j <= B-t else p)
            assert sum(H in N for H in level) == (1 if j <= B-t else 0)
        ratio = Fraction(len(N), len(L))
        if (p, B, t, r) == (3, 1, 1, 2):
            assert ratio == Fraction(1, 2)
            print('FIDELITY source section 4: S3, order=6, normal=3, total=6, ndeg=1/2')
        if (p, B, t, r) == (5, 5, 2, 2):
            assert ratio == Fraction(1, 2)
        print(f'DIRECT p={p} B={B} t={t} r={r} order={p*m} '
              f'normal={len(N)} total={len(L)} ndeg={ratio}')
    print(f'DIRECT_CASES={len(cases)} MAX_ORDER={max(p*2**B for p,B,t,r in cases)}')


def realization_parameters():
    count = 0
    for v in range(2, 11):
        for u in range(1, v):
            d = v-u
            t = 2*d
            q = 2**t
            # Exact search for a prime congruent to 1 modulo q.
            k = 1
            while not prime(k*q+1):
                k += 1
            p = k*q+1
            g = 2
            while pow(pow(g, k, p), q//2, p) == 1:
                g += 1
                assert g < p
            r = pow(g, k, p)
            assert pow(r, q, p) == 1 and pow(r, q//2, p) != 1
            B = p*u+d-1
            assert B >= t >= 1
            N = 2*B-t+2
            L = N+p*t
            assert N == 2*p*u and L == 2*p*v
            assert Fraction(N, L) == Fraction(u, v)
            # No multiplication table for these large groups is claimed.
            print(f'PARAMETERS u={u} v={v} t={t} p={p} r={r} B={B} '
                  f'predicted_normal={N} predicted_total={L} ratio={Fraction(N,L)}')
            count += 1
    # The search seat's explicit example uses r=2 of order 4 modulo 5.
    assert multiplicative_order(2, 5) == 4
    assert (2*10-2+2, 2*10-2+2+5*2) == (20, 30)
    assert Fraction(20, 30) == Fraction(2, 3)
    print(f'PARAMETER_CASES={count}; EXAMPLE order=5120 predicted_normal=20 predicted_total=30')
    print('BOUNDARY x=1: the trivial finite group has exactly one subgroup, which is normal')


def main():
    direct_checks()
    realization_parameters()
    print('ALL_CHECKS_OK')


if __name__ == '__main__':
    main()
