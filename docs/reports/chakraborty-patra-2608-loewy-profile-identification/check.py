#!/usr/bin/env python3
"""Exact finite checks for Chakraborty--Patra, arXiv:2608.14618v1, Conjecture 4.11.

Uses Python's standard library only. These checks test transcription and finite
instances of the proposed proof route; they do not prove the conjecture.
"""
from collections import Counter
from fractions import Fraction
from itertools import combinations_with_replacement, product
from math import comb, factorial, gcd, prod


def q(n, k):
    assert n >= 1 and k >= 2
    return Fraction(comb(k + n - 1, n - 1), (n + 1) ** k)


def profile_zeta(profile, k):
    return prod((1 - q(n, k) for n in profile), start=Fraction(1))


def cyclic_ideals(modulus):
    # All ideals in Z/modulus are additive subgroups, hence cyclic.
    # Enumerate the distinct principal ideals by their actual residue sets.
    return sorted({frozenset(a * x % modulus for x in range(modulus))
                   for a in range(modulus)}, key=lambda s: (len(s), sorted(s)))


def ideal_product(left, right, modulus):
    # The additive subgroup generated by every product x*y is the ideal product.
    generator = modulus
    for x in left:
        for y in right:
            generator = gcd(generator, x * y % modulus)
    return frozenset(range(0, modulus, generator))


def ring_ideal_counts(modulus, max_k):
    ideals = cyclic_ideals(modulus)
    lookup = {I: i for i, I in enumerate(ideals)}
    table = [[lookup[ideal_product(I, J, modulus)] for J in ideals] for I in ideals]
    state = Counter({lookup[frozenset(range(modulus))]: 1})
    result = {}
    for k in range(1, max_k + 1):
        nxt = Counter()
        for i, count in state.items():
            for j in range(len(ideals)):
                nxt[table[i][j]] += count
        state = nxt
        assert sum(state.values()) == len(ideals) ** k
        result[k] = (state[lookup[frozenset({0})]], len(ideals) ** k)
    return ideals, result


def main():
    # Source fidelity: Corollary 4.9 and the discussion after Remark 4.10.
    count_cases = 0
    for n in range(1, 9):
        ideals, counts = ring_ideal_counts(2 ** n, 12)
        assert len(ideals) == n + 1
        for k in range(2, 13):
            numerator, denominator = counts[k]
            assert denominator - numerator == comb(k + n - 1, n - 1)
            assert Fraction(numerator, denominator) == 1 - q(n, k)
            assert 0 < q(n, k) < 1
            count_cases += 1
        assert Fraction(*counts[2]) == Fraction(n + 2, 2 * (n + 1))
    assert profile_zeta((2, 5), 2) == Fraction(7, 18)
    assert profile_zeta((3, 3), 2) == Fraction(25, 64)
    assert profile_zeta((2, 5), 2) != profile_zeta((3, 3), 2)
    print('FIDELITY: zeta_2(2,5)=7/18; zeta_2(3,3)=25/64')
    print(f'RING_IDEAL_COUNTS: {count_cases} cases; Z/(2^n), 1<=n<=8, 2<=k<=12')

    # Independent enumeration of exponent tuples and the slack-coordinate map.
    slack_cases = 0
    for n in range(1, 7):
        for k in range(2, 7):
            nonzero = [a for a in product(range(n + 1), repeat=k) if sum(a) < n]
            slack = {a + (n - 1 - sum(a),) for a in nonzero}
            assert len(slack) == len(nonzero) == comb(k + n - 1, n - 1)
            assert all(sum(a) == n - 1 and min(a) >= 0 for a in slack)
            assert {a[:-1] for a in slack} == set(nonzero)
            slack_cases += 1
    print(f'SLACK_BIJECTION: {slack_cases} exhaustive cases; 1<=n<=6, 2<=k<=6')

    # Exact identity needed for the ordered-scale estimate, including a=1.
    ratio_cases = 0
    for a in range(1, 9):
        for b in range(a + 1, 9):
            for k in range(2, 17):
                ratio = (Fraction(factorial(a - 1), factorial(b - 1))
                         * prod(k + j for j in range(a, b))
                         * Fraction(a + 1, b + 1) ** k)
                assert q(b, k) / q(a, k) == ratio
                assert prod(k + j for j in range(a, b)) <= (b * k) ** (b - a)
                ratio_cases += 1
    print(f'ORDERED_SCALE_IDENTITIES: {ratio_cases} exact cases; 1<=a<b<=8, 2<=k<=16')

    # All sorted profiles in this finite box, including empty and repeated profiles.
    profiles = [p for size in range(6)
                for p in combinations_with_replacement(range(1, 9), size)]
    signatures = {}
    telescoping_cases = cancellation_cases = 0
    for profile in profiles:
        signature = tuple(profile_zeta(profile, k) for k in range(2, 17))
        assert signature not in signatures, (profile, signatures.get(signature))
        signatures[signature] = profile
        for k in range(2, 9):
            prefix, telescoping = Fraction(1), Fraction(0)
            for n in profile:
                telescoping += q(n, k) * prefix
                prefix *= 1 - q(n, k)
            assert 1 - profile_zeta(profile, k) == telescoping
            telescoping_cases += 1
            if profile:
                a = min(profile)
                multiplicity = profile.count(a)
                rest = tuple(n for n in profile if n != a)
                assert profile_zeta(profile, k) / (1 - q(a, k)) ** multiplicity == profile_zeta(rest, k)
                cancellation_cases += 1
    print(f'PROFILE_IDENTIFICATION: {len(profiles)} profiles; 0<=size<=5, lengths 1..8; k=2..16 signatures distinct')
    print(f'TELESCOPING: {telescoping_cases} exact cases; CANCELLATION: {cancellation_cases} exact cases')
    print('BOUNDARY: length 1, repeated lengths, and empty profiles included')
    print('SCOPE: finite exact evidence only; no numerical limit test and no Lean proof')
    print('ALL_CHECKS_OK')


if __name__ == '__main__':
    main()
