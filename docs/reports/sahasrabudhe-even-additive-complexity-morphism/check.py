#!/usr/bin/env python3
"""Exact small checks for the Sahasrabudhe construction question.

The calculations use SymPy algebraic numbers and integer arithmetic only.  The
first check reproduces the paper's d-dimensional Sturmian value d+1 on a large
exact orbit sample.  The second exhausts all two-letter codes of lengths at
most two over {-1,0,1}; for every code with a common codeword slope it checks
the complementary-factor involution and odd cardinality at every small
admissible multiple of the gcd of the codeword lengths.
"""

from itertools import product
from math import gcd
from sympy import floor, sqrt


def sturmian_symbol(n, alphas):
    return sum(floor((n + 1) * a) - floor(n * a) for a in alphas)


def sturmian_complexity(length, alphas, samples=250):
    sums = set()
    for start in range(samples):
        sums.add(sum(sturmian_symbol(start + j, alphas) for j in range(length)))
    return sums


def image(word, code):
    out = []
    for letter in word:
        out.extend(code[letter])
    return out


def semigroup_conductor(lengths):
    """Small exact conductor: least C after which all multiples of gcd occur."""
    d = 0
    for length in lengths:
        d = gcd(d, length)
    reachable = {0}
    for x in range(1, 200):
        if any(x >= length and x - length in reachable for length in lengths):
            reachable.add(x)
    for candidate in range(0, 100):
        if all(x in reachable for x in range(candidate, 100) if x % d == 0):
            return candidate
    raise AssertionError((lengths, reachable))


def universal_sum_set(n, code, source_length):
    """Exact factor sums generated by every binary source word of this length."""
    values = set()
    for source in product((0, 1), repeat=source_length):
        out = image(source, code)
        for start in range(0, len(out) - n + 1):
            values.add(sum(out[start : start + n]))
    return values


def check_sturmian_fidelity():
    # 1, sqrt(2), sqrt(3) are Q-linearly independent, so the paper's Lemma 1
    # predicts d+1=3 values for every positive window length.
    alphas = (sqrt(2), sqrt(3))
    for length in range(1, 21):
        values = sturmian_complexity(length, alphas)
        assert len(values) == 3, (length, values)


def check_even_obstruction_small_cases():
    alphabet_values = (-1, 0, 1)
    words = [tuple(values) for size in (1, 2) for values in product(alphabet_values, repeat=size)]
    checked = 0
    for left in words:
        for right in words:
            code = (left, right)
            lengths = (len(left), len(right))
            sums = (sum(left), sum(right))
            # The common-slope condition is the bounded-complexity prerequisite.
            if sums[0] * lengths[1] != sums[1] * lengths[0]:
                continue
            d = gcd(*lengths)
            conductor = semigroup_conductor(lengths)
            max_len = 6
            for n in range(1, max_len + 1):
                if n % d or n < conductor + 2 * max(lengths):
                    continue
                # A length-n factor intersects at most n+2 codewords here;
                # source_length n+4 therefore contains every needed factor.
                values = universal_sum_set(n, code, n + 4)
                slope_num, slope_den = sums[0], lengths[0]
                center_num = n * slope_num
                assert center_num % slope_den == 0
                center = center_num // slope_den
                assert center in values, (code, n, values, center)
                reflected = {2 * center - value for value in values}
                assert reflected == values, (code, n, values, reflected)
                assert len(values) % 2 == 1, (code, n, values)
                checked += 1
    assert checked > 0


if __name__ == "__main__":
    check_sturmian_fidelity()
    check_even_obstruction_small_cases()
    print("ALL_CHECKS_OK")
