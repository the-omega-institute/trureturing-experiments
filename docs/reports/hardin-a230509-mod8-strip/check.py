    matrix = [[[int(i == j), -T[i][j]] for j in range(5)] for i in range(5)]
    denominator = det(matrix)
    assert denominator == [1, -5, 4, 5, -9, -12]
    # adj(M)[0,3] = cofactor(M)[3,0] = (-1)^(3+0) det M_(3,0).
    minor = [[matrix[i][j] for j in range(5) if j != 0] for i in range(5) if i != 3]
    adjugate_14 = [-c for c in det(minor)]
    assert adjugate_14 == [0, 0, 0, 1, -1]
    assert mul([0, 2], adjugate_14) == [0, 0, 0, 0, 2, -2]
    identity = [[int(i == j) for j in range(5)] for i in range(5)]
    powers = [identity]
    for _ in range(5):
        powers.append(matmul(powers[-1], T))
    coefficients = [-12, -9, 5, 4, -5, 1]
    assert all(sum(coefficients[k] * powers[k][i][j] for k in range(6)) == 0
               for i in range(5) for j in range(5))
    # Adapt the terminal basis vector to scalarRelationShift's all-ones vector.
    p = [[int(i == j) - int(i != 3 and j == 3) for j in range(5)] for i in range(5)]
    pinv = [[int(i == j) + int(i != 3 and j == 3) for j in range(5)] for i in range(5)]
    assert matmul(p, pinv) == matmul(pinv, p) == identity
    assert [sum(row) for row in p] == [0, 0, 0, 1, 0]
    q = matmul(matmul(pinv, T), p)
    assert matmul(p, q) == matmul(T, p)
    q_powers = [identity]
    for _ in range(5):
        q_powers.append(matmul(q_powers[-1], q))
    assert all(sum(coefficients[k] * sum(q_powers[k][i]) for k in range(6)) == 0
               for i in range(5))
    print(f'DET_I_MINUS_XT: {denominator} (ascending powers)')
    print(f'ADJUGATE_1_4: {adjugate_14} (ascending powers)')
    print('ANNIHILATOR: T^5 - 5T^4 + 4T^3 + 5T^2 - 9T - 12I = 0')
