#!/usr/bin/env python3
"""Exact checks for Benfield--Lippard Conjecture 10.4.

The semigroup of offsets is generated by h(n)=n**k-1 (n>=2).  The finite
computation below only checks the published k=2,...,9 table and the structural
identity on a bounded interval; all arithmetic is integer arithmetic.
"""
from __future__ import annotations

TABLE = {
    2: (13, 7), 3: (149, 75), 4: (2641, 1321), 5: (6261, 3175),
    6: (711649, 355825), 7: (249077, 127839),
    8: (1890241, 945121), 9: (6464397, 3438463),
}


def closure(limit: int, generators: list[int]) -> bytearray:
    """Membership in the additive submonoid generated by generators."""
    seen = bytearray(limit + 1)
    seen[0] = 1
    for g in sorted(set(generators)):
        if g <= limit:
            for n in range(g, limit + 1):
                if seen[n - g]:
                    seen[n] = 1
    return seen


def power_generators(k: int, limit: int) -> list[int]:
    return [n**k - 1 for n in range(2, limit + 2) if n**k - 1 <= limit]


def T_generators(k: int, limit: int) -> list[int]:
    m = 2**k - 1
    return [m] + [((u**k - 1) // 2) for u in range(3, limit + 2, 2)
                  if (u**k - 1) // 2 <= limit]


def check_table() -> None:
    for k, (expected_max, expected_count) in TABLE.items():
        seen = closure(expected_max, power_generators(k, expected_max))
        gaps = [n for n in range(1, expected_max + 1) if not seen[n]]
        got = (max(gaps), len(gaps))
        assert got == (expected_max, expected_count), (k, got, (expected_max, expected_count))
        assert expected_max % 2 == 1 and expected_count % 2 == 1
        print(f"fidelity k={k}: a_k={got[0]}, b_k={got[1]} (published table)")


def check_duplication(k: int, bound: int) -> None:
    m = 2**k - 1
    s = closure(bound, power_generators(k, bound))
    t = closure(bound, T_generators(k, bound))
    for n in range(bound + 1):
        rhs = (n % 2 == 0 and t[n // 2] == 1) or (
            n >= m and (n - m) % 2 == 0 and t[(n - m) // 2] == 1
        )
        assert bool(s[n]) == rhs, (k, n, bool(s[n]), rhs)
    gaps_t = [r for r in range(1, bound + 1) if not t[r]]
    F, g = max(gaps_t), len(gaps_t)
    gaps_s = [n for n in range(1, bound + 1) if not s[n]]
    expected = ({2*r for r in gaps_t if 2*r <= bound}
                | {r for r in range(1, m, 2) if r <= bound}
                | {m + 2*r for r in gaps_t if m + 2*r <= bound})
    assert set(gaps_s) == expected, (k, len(gaps_s), len(expected))
    assert (m + 2*F) % 2 == 1
    assert (2*g + (m - 1)//2) % 2 == 1
    print(f"duplication k={k}: S=2T union (m+2T) through {bound}; F={F}, |G|={g}")


def main() -> None:
    check_table()
    for k, bound in ((2, 500), (3, 2000), (4, 10000), (5, 30000)):
        check_duplication(k, bound)
    print("ALL_CHECKS_OK")


if __name__ == "__main__":
    main()
