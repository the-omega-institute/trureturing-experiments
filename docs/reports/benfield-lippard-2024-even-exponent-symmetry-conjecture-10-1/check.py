"""Benfield-Lippard, arXiv:2404.08193v2, Section 10.1: Conjecture 10.1 (a_{2k} = 2 b_{2k} - 1) fails at exponent 14.

B^k is the set of positive gaps of the additive monoid S_k generated by x^k - 1 (x >= 2), so a_k is its Frobenius
number and b_k its genus. For exponents 2..16 the script computes the Apery set of S_k with respect to m = 2^k - 1 by
Dijkstra over residues, then a_k = max Ap - m and b_k = (sum Ap - m(m-1)/2)/m (Selmer). It reproduces Table 2 of the
source (k = 2..9), checks Conjecture 10.4 (both odd) and the symmetry a_k = 2 b_k - 1. For k = 14 it confirms the failure
independently: F = a_14 and a gap h with F - h also a gap are shown not to lie in S_14 by exhaustive search over the
generators below F + m, and it writes the certificate cert14.json: for every residue r mod m an explicit representation
w_r = m*c0 + sum_i c_i (x_i^14 - 1) with w_r = r (mod m) and w_r <= F + m, which proves every n > F lies in S_14.
"""
import heapq
import json
import sys

TABLE = {2: (13, 7), 3: (149, 75), 4: (2641, 1321), 5: (6261, 3175), 6: (711649, 355825), 7: (249077, 127839),
         8: (1890241, 945121), 9: (6464397, 3438463)}


def apery(k):
    m = 2 ** k - 1
    gens = [x ** k - 1 for x in range(2, 64)]
    best = [None] * m
    best[0] = (0, ())
    pq = [(0, 0, ())]
    seen = [False] * m
    while pq:
        dist, r, rep = heapq.heappop(pq)
        if seen[r]:
            continue
        seen[r] = True
        for i, g in enumerate(gens):
            nr = (r + g) % m
            nd = dist + g
            if best[nr] is None or nd < best[nr][0]:
                best[nr] = (nd, rep + (i,))
                heapq.heappush(pq, (nd, nr, rep + (i,)))
    return m, gens, best


ok = True
for k in range(2, 17):
    m, gens, best = apery(k)
    ap = [w for w, _ in best]
    F = max(ap) - m
    total = sum(ap) - m * (m - 1) // 2
    assert total % m == 0
    g = total // m
    sym = F == 2 * g - 1
    table_ok = k not in TABLE or TABLE[k] == (F, g)
    ok = ok and table_ok and F % 2 == 1 and g % 2 == 1 and (sym == (k != 14) if k % 2 == 0 else True)
    print(f"k={k}: a_k={F} b_k={g} odd {F % 2 == 1} {g % 2 == 1}; a_k = 2b_k - 1: {sym}; table {table_ok}")
    if k == 14:
        m14, gens14, best14, F14 = m, gens, best, F

m, gens, best, F = m14, gens14, best14, F14
big = [x for x in gens if x <= F + m and x != m]


def in_S(n):
    g1, g2, g3 = big
    inv = pow(g1 % m, -1, m)
    for d in range(n // g3 + 1):
        for c in range((n - d * g3) // g2 + 1):
            r2 = n - d * g3 - c * g2
            b0 = (r2 * inv) % m
            if g1 * b0 <= r2:
                return True
    return False


h = next(best[r][0] - m for r in range(1, m) if best[r][0] > m and (F - best[r][0] + m) < best[(F - best[r][0] + m) % m][0])
print(f"k=14: F = {F}; F in S: {in_S(F)}; witness h = {h}: h in S {in_S(h)}, F - h in S {in_S(F - h)}")
ok = ok and not in_S(F) and not in_S(h) and not in_S(F - h)
cert = []
for r in range(m):
    w, rep = best[r]
    coeffs = {}
    for i in rep:
        coeffs[i + 2] = coeffs.get(i + 2, 0) + 1
    assert sum(c * (x ** 14 - 1) for x, c in coeffs.items()) == w and w % m == r and w <= F + m
    cert.append({"r": r, "w": w, "coeffs": {str(x): c for x, c in sorted(coeffs.items())}})
json.dump({"k": 14, "m": m, "F": F, "witness_h": h, "apery": cert}, open(sys.argv[1] if len(sys.argv) > 1 else "cert14.json", "w"))
print(f"certificate: {len(cert)} residues, every w_r a sum of generators, w_r = r (mod m), w_r <= F + m")
print("RESULT PASS" if ok else "RESULT FAIL")
sys.exit(0 if ok else 1)
