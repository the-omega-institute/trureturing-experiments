"""Benfield-Lippard, arXiv:2404.08193v2, Conjecture 10.1: minimal generators of S_k = <x^k - 1 : x >= 2> for k = 2..16.

For each k the script computes the Apery set of S_k with respect to m = 2^k - 1, the Frobenius number F and genus g, and
the minimal generators x^k - 1 (x >= 3) below F + m: those not divisible by m whose value equals the Apery element of
their residue. For each minimal generator it prints the gcd of the other minimal generators (m included). For k = 14,
where S_k is minimally generated by m, 3^14 - 1 and 5^14 - 1, it tests the three gluings of a complete intersection
(Herzog: a 3-generated numerical semigroup is symmetric iff it is a complete intersection, iff for some generator n_i
with d = gcd of the other two, d > 1 and n_i lies in the semigroup generated by the other two divided by d).
"""
import heapq
import math


def apery(k, X=64):
    m = 2 ** k - 1
    gens = [x ** k - 1 for x in range(2, X)]
    best = [None] * m
    best[0] = 0
    pq = [(0, 0)]
    seen = [False] * m
    while pq:
        d, r = heapq.heappop(pq)
        if seen[r]:
            continue
        seen[r] = True
        for g in gens:
            nr, nd = (r + g) % m, d + g
            if best[nr] is None or nd < best[nr]:
                best[nr] = nd
                heapq.heappush(pq, (nd, nr))
    return m, best


def in_two(n, a, b):
    """n in <a, b> for coprime a, b."""
    for c in range(n // b + 1):
        if (n - c * b) % a == 0:
            return True
    return False


for k in range(2, 17):
    m, ap = apery(k)
    F = max(ap) - m
    g = (sum(ap) - m * (m - 1) // 2) // m
    mins = [x for x in range(3, 64) if x ** k - 1 <= F + m and (x ** k - 1) % m and ap[(x ** k - 1) % m] == x ** k - 1]
    gs = [x ** k - 1 for x in mins]
    cof = [math.gcd(m, *[y for y in gs if y != G]) for G in gs]
    print(f"k={k}: {'symmetric' if F == 2 * g - 1 else 'not symmetric'}; minimal generators x^k - 1 for x in {mins}; "
          f"gcd of the others {cof}")
    if k == 14:
        n = [m] + gs
        assert len(n) == 3
        glue = []
        for i in range(3):
            o = [n[j] for j in range(3) if j != i]
            d = math.gcd(*o)
            glue.append(d > 1 and in_two(n[i], o[0] // d, o[1] // d))
        print(f"k=14: generators {n}; gluing possible at each generator: {glue}; complete intersection: {any(glue)}")
