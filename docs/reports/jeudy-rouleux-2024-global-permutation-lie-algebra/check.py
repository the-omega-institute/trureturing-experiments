#!/usr/bin/env python3
"""Jeudy-Rouleux (arXiv:2411.03952v1, Section 3.1): is the Schrodinger Hamiltonian H = sum_{i<j} P_ij
in the Lie algebra L generated by Q(alpha) = Qt(alpha)^{(x)N}, alpha a permutation of the d spin labels?

For each (d, N): computes L as the commutator closure of span{Q(alpha)}, tests H in L by a rank test,
and checks the commutant witness O_12 = diagonal projector onto {x_1 = x_2}: [Q(alpha), O_12] = 0 for all
alpha and [H, O_12] != 0. Exit 0 and RESULT PASS when H is outside L in every case and the witness works.
"""
import itertools, sys
import numpy as np

def configs(d, N):
    return list(itertools.product(range(d), repeat=N))

def Qmat(d, N, a):
    C = configs(d, N); idx = {c: i for i, c in enumerate(C)}
    M = np.zeros((len(C), len(C)))
    for j, y in enumerate(C):
        M[idx[tuple(a[s] for s in y)], j] = 1
    return M

def exch(d, N, i, k):
    C = configs(d, N); idx = {c: n for n, c in enumerate(C)}
    M = np.zeros((len(C), len(C)))
    for j, y in enumerate(C):
        x = list(y); x[i], x[k] = x[k], x[i]
        M[idx[tuple(x)], j] = 1
    return M

def rank(vs):
    return np.linalg.matrix_rank(np.array([v.ravel() for v in vs]), tol=1e-8) if vs else 0

def lie_closure(gens):
    basis = []
    for g in gens:
        if rank(basis + [g]) > len(basis): basis.append(g)
    changed = True
    while changed:
        changed = False
        for A in list(basis):
            for B in list(basis):
                c = A @ B - B @ A
                if rank(basis + [c]) > len(basis): basis.append(c); changed = True
    return basis

ok = True
for d, N in [(3, 3), (2, 3), (2, 4), (3, 4), (4, 3)]:
    gens = [Qmat(d, N, a) for a in itertools.permutations(range(d))]
    L = lie_closure(gens)
    H = sum(exch(d, N, i, k) for i in range(N) for k in range(i + 1, N))
    inL = rank(L + [H]) == len(L)
    P23 = exch(d, N, 1, 2)
    p23inL = rank(L + [P23]) == len(L)
    O = np.diag([1.0 if c[0] == c[1] else 0.0 for c in configs(d, N)])
    comm_ok = all(np.allclose(g @ O, O @ g) for g in gens)
    hcomm = np.abs(H @ O - O @ H).max()
    print(f"d={d} N={N} dimL={len(L)} H_in_L={inL} P23_in_L={p23inL} Q_commute_O12={comm_ok} max|[H,O12]|={hcomm:.0f}")
    if inL or p23inL or not comm_ok or hcomm < 0.5: ok = False
print("RESULT", "PASS" if ok else "FAIL")
sys.exit(0 if ok else 1)
