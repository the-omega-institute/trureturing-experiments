"""Tarnauceanu, Sci. Stud. Res. Ser. Math. Inform. 34 (2024) 115-120, Conjecture 3.1.

f(G) = sum over all subgroups H of G of 1/|H|. Claim: there is no constant c > 1 with
f(G) > c for all finite non-cyclic groups G, i.e. inf f over finite non-cyclic groups is 1.

Family: G = C_p x| C_{q^s}, q, p primes, q | p - 1, the generator of C_{q^s} acting on C_p by
an automorphism of order q. Subgroups (exhaustive): the inverse images of the s + 1 subgroups
of C_{q^s} (orders p q^j, 0 <= j <= s), the s proper subgroups of the complement (orders q^j,
0 <= j < s), and the p conjugates of the complement (order q^s). Hence
    f = sum_{j=0}^{s} 1/(p q^j) + sum_{j=0}^{s-1} 1/q^j + p/q^s.
"""
import sys
from fractions import Fraction as Fr
from itertools import product

ok = True
def check(name, cond):
    global ok
    print(("PASS " if cond else "FAIL ") + name); ok = ok and bool(cond)

def formula(p, q, s):
    return sum(Fr(1, p * q**j) for j in range(s + 1)) + sum(Fr(1, q**j) for j in range(s)) + Fr(p, q**s)

def group(p, q, s):
    # find r of multiplicative order q mod p
    r = next(r for r in range(2, p) if pow(r, q, p) == 1 and r % p != 1)
    n = q**s
    elems = [(a, b) for a in range(p) for b in range(n)]
    def mul(x, y):
        (a, b), (c, d) = x, y
        return ((a + pow(r, b, p) * c) % p, (b + d) % n)
    return elems, mul

def subgroups(elems, mul):
    e = (0, 0)
    def closure(gens):
        S = {e}; frontier = [e]
        while frontier:
            new = []
            for x in frontier:
                for g in gens:
                    y = mul(x, g)
                    if y not in S:
                        S.add(y); new.append(y)
            frontier = new
        return frozenset(S)
    cyc = {closure([g]) for g in elems}
    subs = set(cyc)
    # metacyclic groups: every subgroup is generated by at most two elements
    cl = list(cyc)
    for A in cl:
        for B in cl:
            subs.add(closure(list(A | B)))
    return subs

for (p, q, s) in [(7, 3, 1), (7, 3, 2), (5, 2, 3), (13, 3, 2), (11, 5, 1)]:
    elems, mul = group(p, q, s)
    subs = subgroups(elems, mul)
    f = sum(Fr(1, len(H)) for H in subs)
    nonab = any(mul(x, y) != mul(y, x) for x in elems for y in elems)
    check(f"p={p} q={q} s={s}: {len(subs)} subgroups (= 2s+p+1 = {2*s+p+1}), f = {f} = formula {formula(p,q,s)}, nonabelian {nonab}",
          len(subs) == 2 * s + p + 1 and f == formula(p, q, s) and nonab)

def prime(n):
    return n > 1 and all(n % d for d in range(2, int(n**0.5) + 1))

# Upper bound: f < 1/(p-1) + q/(q-1) + p/q^s < 1 + 1/(p-1) + 1/(q-1) + p/q^s; take q large, p = 1 mod q, s large.
print("q, p (least prime = 1 mod q), s, f, f - 1:")
prev = None
for q in [3, 5, 11, 23, 47, 101]:
    p = next(m for m in range(q + 1, 10**7) if m % q == 1 and prime(m))
    s = 1
    while Fr(p, q**s) >= Fr(1, q): s += 1
    f = formula(p, q, s)
    print(f"  q={q} p={p} s={s} f-1={float(f-1):.6f}  bound 3/(q-1)={3/(q-1):.6f}")
    check(f"q={q}: 1 < f < 1 + 3/(q-1)", 1 < f < 1 + Fr(3, q - 1))
print("RESULT", "PASS" if ok else "FAIL")
sys.exit(0 if ok else 1)
