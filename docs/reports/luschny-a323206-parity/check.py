#!/usr/bin/env python3
"""Exact finite checks of Peter Luschny's OEIS A323206 parity conjecture.

The fixed data are OEIS A323206 revision 52, EXAMPLE rows n=0,...,8.
The computation is evidence on the printed ranges, not a uniform proof.
"""
from fractions import Fraction
from math import comb, factorial, prod


SOURCE_ROWS = (
    (1, 1, 1, 1, 1, 1, 1, 1),
    (1, 2, 5, 14, 42, 132, 429, 1430),
    (1, 3, 13, 67, 381, 2307, 14589, 95235),
    (1, 4, 25, 190, 1606, 14506, 137089, 1338790),
    (1, 5, 41, 413, 4641, 55797, 702297, 9137549),
    (1, 6, 61, 766, 10746, 161376, 2537781, 41260086),
    (1, 7, 85, 1279, 21517, 387607, 7312789, 142648495),
    (1, 8, 113, 1982, 38886, 817062, 17981769, 409186310),
    (1, 9, 145, 2905, 65121, 1563561, 39322929, 1022586105),
)
MAX_K = 100
MAX_N = 20


def choose(n, r):
    """Ordinary binomial, extended by zero outside 0 <= r <= n."""
    return comb(n, r) if 0 <= r <= n else 0


def pochhammer(a, j):
    return prod(a + t for t in range(j))


def hypergeometric_coeff(k, j):
    denominator = pochhammer(-k - 1, j) * factorial(j)
    assert denominator != 0, (k, j)
    return Fraction(pochhammer(-k, j) * pochhammer(k + 1, j), denominator)


def ballot_coeff(k, j):
    return choose(k + j, j) - choose(k + j, j - 1)


def evaluate(coeffs, n):
    value = Fraction(0)
    for c in reversed(coeffs):
        value = value * n + c
    return value


def is_power_of_two(m):
    return m > 0 and m & (m - 1) == 0


def main():
    # Build ordinary Catalan numbers independently by first-return convolution.
    catalan = [1]
    for m in range(MAX_K + 1):
        catalan.append(sum(catalan[i] * catalan[m - i] for i in range(m + 1)))
    for m, c in enumerate(catalan):
        assert (m + 1) * c == comb(2 * m, m), m

    coeffs = []
    coefficient_count = 0
    for k in range(MAX_K + 1):
        row = tuple(hypergeometric_coeff(k, j) for j in range(k + 1))
        for j, c in enumerate(row):
            assert c == Fraction(comb(k + j, k)) * (1 - Fraction(j, k + 1)), (k, j)
            assert c == ballot_coeff(k, j), (k, j)
            assert c.denominator == 1, (k, j)
            coefficient_count += 1
        assert row[0] == 1, k
        assert sum(row) == catalan[k + 1], k
        assert sum(choose(k + j, j) for j in range(k + 1)) == choose(2 * k + 1, k), k
        assert sum(choose(k + j, j - 1) for j in range(1, k + 1)) == choose(2 * k + 1, k - 1), k
        coeffs.append(row)

    fidelity_count = 0
    for n, source_row in enumerate(SOURCE_ROWS):
        for k, expected in enumerate(source_row):
            assert evaluate(coeffs[k], n) == expected, (n, k, expected)
            fidelity_count += 1
    print(f"FIDELITY: {fidelity_count} source EXAMPLE entries agree (0 <= n <= 8, 0 <= k <= 7).")
    print(f"COEFFICIENTS: {coefficient_count} exact Pochhammer/ballot coefficients agree (0 <= j <= k <= {MAX_K}).")
    print(f"ROW_SUM: {MAX_K + 1} rows equal Catalan[k+1], independently generated by convolution.")

    pair_count = 0
    for n in range(MAX_N + 1):
        for k in range(MAX_K + 1):
            value = evaluate(coeffs[k], n)
            assert value.denominator == 1, (n, k)
            # The other finite formula, with its original source index order.
            other = sum((choose(2 * k - j, k) - choose(2 * k - j, k + 1)) * n ** (k - j)
                        for j in range(k + 1))
            assert value == other, (n, k)
            expected_odd = n % 2 == 0 or (n % 2 == 1 and is_power_of_two(k + 2))
            assert (value.numerator % 2 == 1) == expected_odd, (n, k, value)
            assert value.numerator % 2 == evaluate(coeffs[k], n % 2).numerator % 2, (n, k)
            pair_count += 1
    print(f"PARITY: {pair_count} pairs pass, including n=0 and k=0 (0 <= n <= {MAX_N}, 0 <= k <= {MAX_K}).")
    print("ALL_CHECKS_OK")


if __name__ == "__main__":
    main()
