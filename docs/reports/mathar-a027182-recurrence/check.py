#!/usr/bin/env python3
"""Exact checks for the OEIS A027182 recurrence conjecture.

All values are Python integers; the operator identity is checked with SymPy's
exact polynomial arithmetic.  No floating-point values are used.
"""

from math import comb

import sympy as sp


def T(n: int, k: int) -> int:
    """A027170(n,k), including the entry's -4 normalization."""
    return 2 * comb(n + 2, k + 1) + comb(n, k) - 4


def a(n: int) -> int:
    """The coefficient [x^n] g_n(x)^2, using row symmetry."""
    return sum(T(n, k) * T(n, n - k) for k in range(n + 1))


def h(n: int) -> int:
    return (
        4 * comb(2 * n + 4, n + 2)
        + 4 * comb(2 * n + 2, n + 1)
        + comb(2 * n, n)
    )


def recurrence_residual(values: list[int], n: int) -> int:
    return (
        2 * (n + 2) * values[n]
        + (-17 * n - 23) * values[n - 1]
        + (47 * n + 36) * values[n - 2]
        + 2 * (-22 * n - 17) * values[n - 3]
        + 4 * (-n + 20) * values[n - 4]
        + 8 * (2 * n - 9) * values[n - 5]
        + 24 * (12 * n - 47)
    )


def main() -> None:
    # Fidelity: the published sequence starts 18, 150, 820, ... .  The
    # explanatory A027182 example says 120 for a(2), but its row arithmetic
    # is 5^2+10^2+5^2 = 150, matching the data and definition.
    assert [a(n) for n in range(1, 6)] == [18, 150, 820, 3726, 15492]
    assert 5 * 5 + 10 * 10 + 5 * 5 == 150
    print("fidelity: A027182 data and row example agree (a(2)=150)")

    # Closed form from the proposed proof outline, including its natural a(0).
    for n in range(26):
        assert a(n) == h(n) - 72 * (2**n) + 16 * n + 40
    print("closed_form: n=0..25")

    values = [a(n) for n in range(31)]
    for n in range(5, 31):
        assert recurrence_residual(values, n) == 0
    print("recurrence: n=5..30 (therefore every published n>=6 is covered)")

    # Exact operator factorization.  B has lags 0,1,2; the claimed left
    # multiplier is 1 - 5E + 8E^2 - 4E^3, with E shifting n to n-1.
    n, z = sp.symbols("n z")
    b = 2 * (n + 2) + (-7 * n - 13) * z + (-4 * n + 6) * z**2
    multiplier = 1 - 5 * z + 8 * z**2 - 4 * z**3
    expected = [
        2 * n + 4,
        -17 * n - 23,
        47 * n + 36,
        -44 * n - 34,
        80 - 4 * n,
        16 * n - 72,
    ]
    def b_at(m):
        return 2 * (m + 2) + (-7 * m - 13) * z + (-4 * m + 6) * z**2

    actual = sp.Poly(
        sp.expand(b_at(n) - 5 * z * b_at(n - 1) + 8 * z**2 * b_at(n - 2) - 4 * z**3 * b_at(n - 3)),
        z,
    )
    # Directly compare the recurrence coefficients generated by
    # B(n), -5B(n-1), 8B(n-2), -4B(n-3).
    composed = [
        sp.expand(2 * (n + 2)),
        sp.expand((-7 * n - 13) - 5 * (2 * (n - 1 + 2))),
        sp.expand((-4 * n + 6) - 5 * (-7 * (n - 1) - 13) + 8 * (2 * (n - 2 + 2))),
        sp.expand(-5 * (-4 * (n - 1) + 6) + 8 * (-7 * (n - 2) - 13) - 4 * (2 * (n - 3 + 2))),
        sp.expand(8 * (-4 * (n - 2) + 6) - 4 * (-7 * (n - 3) - 13)),
        sp.expand(-4 * (-4 * (n - 3) + 6)),
    ]
    assert [sp.expand(x) for x in composed] == expected
    assert [sp.expand(actual.coeff_monomial(z**j)) for j in range(6)] == expected
    print("operator_factorization: exact SymPy polynomial identities")

    print("ALL_CHECKS_OK")


if __name__ == "__main__":
    main()
