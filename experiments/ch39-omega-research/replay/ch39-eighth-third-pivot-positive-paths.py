def verify(root, case):
    high, active, anchors, colour_floor, determinant_floor = CASES[case - 1]
    solve = run_path(str(root / "ch39-fifth-third-pivot-em-colour-path.py"))["solve"]
    data, rows, weights, centers, boxes, weak, lib = solve(
        root, anchors, tuple(i - 1 for i in active), number=2_306_888_100_093
    )
    threshold = arb("1e-6")
    assert all(x > threshold if i in high else x < threshold for i, x in enumerate(boxes, 1))
    # 共用检测器以 2 为色通道的细分阈值。正数倍缩放及其导数界一同传入。
    a1, a2, a3 = data["initial"]
    scaled = dict(data, initial=(a1, a2, 3 * a3))
    species = [(k, m, (q, b, 3 * c)) for k, m, (q, b, c) in rows]
    path = lib("fourth-third-pivot-neutral-positive-path")["path"]
    leaves, floors = path(scaled, species, weights, centers, boxes, weak, lib)
    colour, determinant = floors[2] / 3, floors[3]
    assert colour > arb(colour_floor) and determinant > arb(determinant_floor)
    print("高层、闭段数、实际色与中性行列式下界", high, leaves, colour.str(12), determinant.str(12))
    return colour, determinant


