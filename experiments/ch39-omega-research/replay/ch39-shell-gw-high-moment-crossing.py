def fitted_direction():
    ck,du,dd=model["m"]["orb"]["reference"]()
    U,A,B=[model["m"]["four"]["exact_frame"](np.array(z).reshape(3,3)) for z in units]
    u,d=U*du*A*model["up"][-1],U*ck*dd*B*model["down"][-1]
    target=acb_mat([[z] for z in u.entries()+d.conjugate().entries()])
    t=n["relative_phase"](arb(676))
    P=acb_mat(rows(model["F"])+rows(kin["arc"]["conjugate_output"](t)))
    y=acb_mat([[acb(x,z)] for x,z in seed])
    y=y+adj(P)*(P*adj(P)).solve(target-P*y)
    norm=hs(y,y).real.sqrt()
    assert norm < 4*arb.pi()
    return m["site_frame"]()*y/norm


def moment(v,mass,degree):
    x=s["w"]["diagonal"]([acb_mat(3,3,[v[9*i+j,0]*mass.sqrt() for j in range(9)]) for i in range(6)])
    D=s["w"]["full"](s["a"],s["b"],x)/4
    return s["w"]["trace"](D**degree).real


if __name__=="__main__":
    v=fitted_direction()
    sing=m["site_frame"]()*acb_mat([[1/arb(6).sqrt() if i%9==0 else 0] for i in range(54)])
    baseline=moment(v,arb(0),600)
    for mass,lo,hi in ((".0001",".8588",".8589"),(".01",".9115",".9116"),("1","1.11e7","1.12e7")):
        mass=arb(mass)
        ref=moment(sing,mass,600)
        ratio=(moment(v,mass,600)-baseline)/(ref-baseline)
        assert ref>baseline and arb(lo)<ratio<arb(hi)
        print("T",mass.str(4),"600th-moment increment ratio",ratio.str(9))
